"""Hook 06 — eventual-consistency operation table.

The bundled spec metadata marks which operations are eventually consistent: a
read issued immediately after a related write may not observe the write yet.
This hook emits a generated lookup table in the root `camunda` package so the
hand-written `IsEventuallyConsistent` helper (consistency.go) can expose it, and
callers can decide to wrap such reads in `Poll`.

The table is data, not behavior — it simply mirrors
metadata.eventuallyConsistentOps by operationId.
"""
from __future__ import annotations

from pathlib import Path

HEADER = "// Code generated by scripts/hooks/hook_06_consistency.py. DO NOT EDIT.\n\n"


def run(ctx) -> None:
    root: Path = ctx["root"]
    metadata = ctx["metadata"]
    ops = metadata.get("eventuallyConsistentOps", [])

    ids = sorted({o["operationId"] for o in ops if o.get("operationId")})

    lines = [HEADER, "package camunda\n\n"]
    lines.append("// eventuallyConsistentOps maps operationId -> true for operations whose reads\n")
    lines.append("// are eventually consistent. Generated from spec metadata.\n")
    lines.append("var eventuallyConsistentOps = map[string]bool{\n")
    for op_id in ids:
        lines.append(f'\t{_quote(op_id)}: true,\n')
    lines.append("}\n")

    out = root / "consistency_generated.go"
    out.write_text("".join(lines), encoding="utf-8")
    print(f"hook_06_consistency: emitted {len(ids)} operations into {out.name}")


def _quote(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'
