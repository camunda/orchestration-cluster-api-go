"""Hook 02 — union ``*ExactMatch`` wrappers.

Every ``*FilterProperty`` union in the spec has an ``*ExactMatch`` branch that is an
``allOf: [<Key>]`` wrapper (an exact-value match on a semantic key). openapi-generator
references these ``*ExactMatch`` types in the generated union structs but does not emit
them, so the client does not compile.

Each ``<Name>ExactMatch`` is the scalar value of its base key, so this hook emits a Go
type alias to the base key type (defined by hook 01) — or to ``ModelString`` when the
base is not a recognized key. Aliases keep the union (un)marshalling behaviour identical
to a bare scalar.
"""
from __future__ import annotations

import re
from pathlib import Path

_OUT = "zz_generated_union_wrappers.go"
_SUFFIX = "ExactMatch"
_TYPE_DECL = re.compile(r"^type\s+(\w+)\s", re.MULTILINE)
_PKG_DECL = re.compile(r"^package\s+(\w+)", re.MULTILINE)


def _detect_package(client_dir: Path) -> str:
    for name in ("client.go", "configuration.go", "utils.go"):
        p = client_dir / name
        if p.exists():
            m = _PKG_DECL.search(p.read_text(encoding="utf-8"))
            if m:
                return m.group(1)
    return "openapi"


def _existing_types(client_dir: Path) -> set[str]:
    found: set[str] = set()
    for f in client_dir.glob("*.go"):
        if f.name == _OUT:
            continue
        try:
            found.update(_TYPE_DECL.findall(f.read_text(encoding="utf-8")))
        except OSError:
            continue
    return found


def _collect_exact_match_refs(metadata) -> set[str]:
    refs: set[str] = set()
    for union in metadata.get("unions", []):
        for branch in union.get("branches", []):
            ref = branch.get("ref", "")
            if ref.endswith(_SUFFIX):
                refs.add(ref)
    return refs


def run(ctx) -> None:
    client_dir: Path = ctx["client_dir"]
    pkg = _detect_package(client_dir)
    existing = _existing_types(client_dir)  # includes hook 01's key types
    refs = _collect_exact_match_refs(ctx["metadata"])

    lines = [
        "// Code generated by scripts/hooks/hook_02_union_exact_match.py. DO NOT EDIT.",
        "",
        f"package {pkg}",
        "",
        "// *ExactMatch union branches are exact-value matches on a semantic key. Each is",
        "// an alias to its base key type (hook 01) so the generated union structs compile",
        "// and (un)marshal as the underlying scalar.",
    ]
    generated = 0
    for ref in sorted(refs):
        if ref in existing:
            continue
        base = ref[: -len(_SUFFIX)]
        target = base if base in existing else "ModelString"
        lines.append(f"type {ref} = {target}")
        generated += 1

    (client_dir / _OUT).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"    generated {generated} *ExactMatch aliases into {_OUT}")
