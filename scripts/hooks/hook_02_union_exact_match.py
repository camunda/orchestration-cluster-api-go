"""Hook 02 — union ``*ExactMatch`` wrappers.

Every ``*FilterProperty`` union in the spec has an ``*ExactMatch`` branch that is an
``allOf: [<Key>]`` wrapper (an exact-value match on a semantic key). openapi-generator
references these ``*ExactMatch`` types in the generated union structs but does not emit
them, so the client does not compile.

Each ``<Name>ExactMatch`` is the scalar value of its ``allOf`` base — a semantic key
(hook 01) or an enum — so this hook emits a Go type alias to that base type, or to
``ModelString`` when the base is not a known type. Aliases keep the union
(un)marshalling behaviour identical to a bare scalar.

Where openapi-generator *does* emit an ``*ExactMatch`` model, it is an empty struct:
it cannot hold the value, marshals as ``{}``, and fails to decode the scalar. Those
model files are deleted and replaced by the alias.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

_OUT = "zz_generated_union_wrappers.go"
_SUFFIX = "ExactMatch"
_TYPE_DECL = re.compile(r"^type\s+(\w+)\s", re.MULTILINE)
_PKG_DECL = re.compile(r"^package\s+(\w+)", re.MULTILINE)
_STRUCT_DECL = r"^type\s+{name}\s+struct\s*\{{(.*?)^\}}"


def _detect_package(client_dir: Path) -> str:
    for name in ("client.go", "configuration.go", "utils.go"):
        p = client_dir / name
        if p.exists():
            m = _PKG_DECL.search(p.read_text(encoding="utf-8"))
            if m:
                return m.group(1)
    return "camundaapi"


def _existing_types(client_dir: Path) -> dict[str, Path]:
    found: dict[str, Path] = {}
    for f in client_dir.glob("*.go"):
        if f.name == _OUT:
            continue
        try:
            for name in _TYPE_DECL.findall(f.read_text(encoding="utf-8")):
                found[name] = f
        except OSError:
            continue
    return found


def _collect_exact_match_refs(metadata) -> set[str]:
    refs: set[str] = set()
    for union in metadata.get("unions", []):
        for branch in union.get("branches", []):
            ref = branch.get("ref", "")
            if ref.endswith(_SUFFIX):
                refs.add(ref)
    return refs


def _allof_base(name: str, schemas: dict) -> str | None:
    schema = schemas.get(name)
    if not isinstance(schema, dict):
        return None
    bases = [s["$ref"].split("/")[-1] for s in schema.get("allOf", []) or []
             if isinstance(s, dict) and isinstance(s.get("$ref"), str)]
    return bases[0] if len(bases) == 1 else None


def _drop_empty_struct(name: str, path: Path) -> None:
    text = path.read_text(encoding="utf-8")
    m = re.search(_STRUCT_DECL.format(name=re.escape(name)), text, re.MULTILINE | re.DOTALL)
    if not m or m.group(1).strip():
        raise SystemExit(f"hook 02: {name} in {path.name} is not an empty struct; refusing to alias it")
    path.unlink()


def run(ctx) -> None:
    client_dir: Path = ctx["client_dir"]
    pkg = _detect_package(client_dir)
    existing = _existing_types(client_dir)  # includes hook 01's key types
    refs = _collect_exact_match_refs(ctx["metadata"])
    schemas = json.loads(Path(ctx["spec_path"]).read_text(encoding="utf-8"))["components"]["schemas"]

    lines = [
        "// Code generated by scripts/hooks/hook_02_union_exact_match.py. DO NOT EDIT.",
        "",
        f"package {pkg}",
        "",
        "// *ExactMatch union branches are exact-value matches on a key or enum. Each is",
        "// an alias to its base type so the generated union structs compile and",
        "// (un)marshal as the underlying scalar.",
    ]
    generated = replaced = 0
    for ref in sorted(refs):
        if ref in existing:
            _drop_empty_struct(ref, existing.pop(ref))
            replaced += 1
        base = _allof_base(ref, schemas) or ref[: -len(_SUFFIX)]
        target = base if base in existing else "ModelString"
        lines.append(f"type {ref} = {target}")
        generated += 1

    (client_dir / _OUT).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"    generated {generated} *ExactMatch aliases into {_OUT} "
          f"(replacing {replaced} empty generated structs)")
